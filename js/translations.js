  function isLang(x) { return LANGS.indexOf(x) !== -1; }

  /* Decide the first language: address ?lang=ru, then saved choice,
     then the browser's language, then English. */
  function detectLanguage() {
    try {
      var m = /[?&]lang=(en|ru|uz)/.exec(window.location.search || '');
      if (m) { return m[1]; }
    } catch (e1) { /* ignore */ }
    try {
      var saved = window.localStorage.getItem(STORE_KEY);
      if (isLang(saved)) { return saved; }
    } catch (e2) { /* ignore */ }
    try {
      var nav = String(window.navigator.language || '').toLowerCase().slice(0, 2);
      if (isLang(nav)) { return nav; }
    } catch (e3) { /* ignore */ }
    return 'en';
  }

  IO.lang = detectLanguage();

  /* Find a text: chosen language first, then English, else nothing. */
  function lookup(key) {
    var current = T[IO.lang];
    if (current && typeof current[key] === 'string') { return current[key]; }
    var english = T.en;
    if (english && typeof english[key] === 'string') { return english[key]; }
    return null;
  }

  /* Replace {n} style placeholders with real values. */
  function fill(text, vars) {
    if (!vars) { return text; }
    return text.replace(/\{(\w+)\}/g, function (whole, name) {
      return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole;
    });
  }

  /* IO.t('key', 'English fallback', {n: 5})  ->  the text in the chosen language */
  IO.t = function (key, fallback, vars) {
    var text = lookup(key);
    if (text === null) {
      text = (fallback !== undefined && fallback !== null) ? fallback : key;
    }
    return fill(String(text), vars);
  };

  /* For sample data written as {en: "...", ru: "...", uz: "..."} */
  IO.pick = function (obj) {
    if (typeof obj === 'string') { return obj; }
    if (!obj || typeof obj !== 'object') { return ''; }
    return obj[IO.lang] || obj.en || obj.ru || obj.uz || '';
  };

  IO.getLang = function () { return IO.lang; };

  /* Write the chosen language into every marked element on the page. */
  IO.applyTranslations = function (root) {
    try {
      var scope = root || document;
      document.documentElement.setAttribute('lang', IO.lang);

      var plain = scope.querySelectorAll('[data-i18n]');
      for (var i = 0; i < plain.length; i++) {
        var text = lookup(plain[i].getAttribute('data-i18n'));
        if (text !== null) { plain[i].textContent = text; }
      }

      var attrs = [
        ['data-i18n-placeholder', 'placeholder'],
        ['data-i18n-aria', 'aria-label'],
        ['data-i18n-title', 'title']
      ];
      for (var a = 0; a < attrs.length; a++) {
        var list = scope.querySelectorAll('[' + attrs[a][0] + ']');
        for (var j = 0; j < list.length; j++) {
          var t2 = lookup(list[j].getAttribute(attrs[a][0]));
          if (t2 !== null) { list[j].setAttribute(attrs[a][1], t2); }
        }
      }

      var buttons = document.querySelectorAll('[data-lang]');
      for (var b = 0; b < buttons.length; b++) {
        buttons[b].setAttribute('aria-pressed',
          buttons[b].getAttribute('data-lang') === IO.lang ? 'true' : 'false');
      }
    } catch (err) {
      if (IO.reportError) { IO.reportError(err, 'error.generic'); }
    }
  };

  /* Change the language, remember the choice, tell the rest of the site. */
  IO.setLang = function (lang) {
    if (!isLang(lang)) { return; }
    IO.lang = lang;
    try { window.localStorage.setItem(STORE_KEY, lang); } catch (e) { /* ignore */ }
    IO.applyTranslations();
    try {
      document.dispatchEvent(new CustomEvent('inandout:langchange', { detail: { lang: lang } }));
    } catch (e2) { /* ignore */ }
  };

  /* Any button with data-lang="en" / "ru" / "uz" switches the language. */
  document.addEventListener('click', function (event) {
    try {
      var el = event.target;
      var btn = (el && el.closest) ? el.closest('[data-lang]') : null;
      if (!btn) { return; }
      event.preventDefault();
      IO.setLang(btn.getAttribute('data-lang'));
    } catch (err) {
      if (IO.reportError) { IO.reportError(err, 'error.generic'); }
    }
  });

  /* Fill the page as soon as it is ready. */
  function start() { IO.applyTranslations(); }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
